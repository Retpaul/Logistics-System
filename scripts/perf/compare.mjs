// Builds docs/performance/comparison.md from two bench.mjs result sets.
// Usage: npm run perf:compare -- --before baseline --after optimised
import { readFile, writeFile } from "node:fs/promises";

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const beforeLabel = arg("before", "baseline");
const afterLabel = arg("after", "optimised");
const load = async (label) =>
  JSON.parse(await readFile(new URL(`../../docs/performance/${label}/results.json`, import.meta.url), "utf8"));
const before = await load(beforeLabel);
const after = await load(afterLabel);

const f = (n) => (n < 10 ? n.toFixed(2) : n < 100 ? n.toFixed(1) : n.toFixed(0));
const speedup = (b, a) => (a > 0 ? `${(b / a).toFixed(b / a >= 10 ? 0 : 1)}×` : "–");
const access = (r) => r.planNodes.filter((n) => /Scan|Sort|Hash Join|Nested Loop|Aggregate/.test(n)).slice(0, 3).join(" → ");

const lines = [
  `# Query performance: ${beforeLabel} vs ${afterLabel}`,
  "",
  `Generated by \`scripts/perf/compare.mjs\` from \`${beforeLabel}/results.json\` (${before.capturedAt}) and \`${afterLabel}/results.json\` (${after.capturedAt}).`,
  `Latency = client-side round trip on localhost, warm cache, ${after.runs} runs after ${after.warmup} warm-up runs. Execution = server-side \`EXPLAIN ANALYZE\` time. Buffers = shared blocks touched (8 KB pages).`,
  "",
  `| Query | Endpoint | p50 before (ms) | p50 after (ms) | p95 before (ms) | p95 after (ms) | Exec before → after (ms) | Buffers before → after | Speed-up (p50) |`,
  `| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |`,
];
for (const b of before.results) {
  const a = after.results.find((r) => r.id === b.id);
  if (!a) continue;
  const buffers = (r) => (r.sharedHit ?? 0) + (r.sharedRead ?? 0);
  lines.push(`| ${b.id} | \`${b.endpoint}\` | ${f(b.p50)} | ${f(a.p50)} | ${f(b.p95)} | ${f(a.p95)} | ${f(b.executionMs)} → ${f(a.executionMs)} | ${buffers(b)} → ${buffers(a)} | ${speedup(b.p50, a.p50)} |`);
}
lines.push("", "## Plan shape (top access nodes)", "", "| Query | Before | After |", "| --- | --- | --- |");
for (const b of before.results) {
  const a = after.results.find((r) => r.id === b.id);
  if (a) lines.push(`| ${b.id} | ${access(b)} | ${access(a)} |`);
}

const totalIdx = (rep) => rep.tables.reduce((s, t) => s + Number(t.index_bytes), 0);
const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
lines.push(
  "",
  "## Cost of the change",
  "",
  `| Measure | ${beforeLabel} | ${afterLabel} |`,
  "| --- | ---: | ---: |",
  `| Total index size (all tables) | ${mb(totalIdx(before))} | ${mb(totalIdx(after))} |`,
  `| \`Order\` index size | ${before.tables.find((t) => t.table === "Order").indexes} | ${after.tables.find((t) => t.table === "Order").indexes} |`,
  `| \`Payment\` index size | ${before.tables.find((t) => t.table === "Payment").indexes} | ${after.tables.find((t) => t.table === "Payment").indexes} |`,
  `| Insert 10,000 orders (median ms) | ${before.write.medianMs} | ${after.write.medianMs} |`,
  `| Per-row insert cost (µs) | ${before.write.perRowUs} | ${after.write.perRowUs} |`,
  "",
  "## Index usage during the optimised run",
  "",
  "| Table | Index | Size | Scans |",
  "| --- | --- | ---: | ---: |",
  ...after.indexes.filter((i) => ["Order", "Payment"].includes(i.table)).map((i) => `| ${i.table} | ${i.index} | ${i.size} | ${i.scans} |`),
  "",
);

await writeFile(new URL("../../docs/performance/comparison.md", import.meta.url), lines.join("\n"));
console.log(lines.join("\n"));
